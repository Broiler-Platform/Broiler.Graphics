namespace Broiler.Graphics.Rendering;

/// <summary>Cached ASCII glyph patterns for hosts without usable fonts.</summary>
internal static class BBlockFont
{
    private static readonly string[][] Patterns = BuildPatterns();

    internal static string[] GetPattern(char character) => Patterns[character < 128 ? character : 0];

    private static string[][] BuildPatterns()
    {
        var patterns = new string[128][];
        for (int i = 0; i < patterns.Length; i++)
            patterns[i] = CreatePattern((char)i);
        return patterns;
    }

